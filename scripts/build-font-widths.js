'use strict';

/**
 * Measure TH SarabunPSK and write `src/th-sarabun-widths.js`.
 *
 * The DOCX filler has to know how wide a value is before Word ever sees it, so
 * it can work out how much of the blank the value covers. Guessing that from
 * character classes was out by a few percent, which is a whole tab stop over
 * the length of a name; these are the font's own advances, measured once off
 * `web/public/fonts/THSarabunPSK.ttf` at 200px and stored in thousandths of an
 * em.
 *
 * Rerun after replacing the font:  node scripts/build-font-widths.js
 */

const fs = require('fs');
const path = require('path');
const puppeteer = require('puppeteer');

const FONT = path.join(__dirname, '..', 'web', 'public', 'fonts', 'THSarabunPSK.ttf');
const OUT = path.join(__dirname, '..', 'src', 'th-sarabun-widths.js');
const SIZE = 200;

/** The characters a Thai inspection record can hold. */
function codepoints() {
  const points = [];
  for (let c = 0x20; c <= 0x7e; c += 1) points.push(c);
  for (let c = 0x0e00; c <= 0x0e5b; c += 1) points.push(c);
  // Punctuation Word substitutes in, and the form's own check boxes.
  for (const c of [0x2018, 0x2019, 0x201c, 0x201d, 0x2013, 0x2014, 0x2610, 0x2611]) points.push(c);
  return points;
}

(async () => {
  const browser = await puppeteer.launch({ headless: 'new' });
  try {
    const page = await browser.newPage();
    const url = `file:///${FONT.split(path.sep).join('/')}`;
    await page.setContent(
      `<style>@font-face{font-family:S;src:url('${url}')}` +
        `#m{font:${SIZE}px S;white-space:pre;position:absolute}</style><span id=m></span>`
    );
    await page.evaluate(() => document.fonts.ready);

    const widths = await page.evaluate(
      (points, size) => {
        const node = document.getElementById('m');
        const out = {};
        for (const c of points) {
          const ch = String.fromCodePoint(c);
          // Ten copies, so the rounding of one measurement is spread over ten.
          node.textContent = ch.repeat(10);
          out[c] = Math.round((node.getBoundingClientRect().width / 10 / size) * 1000);
        }
        return out;
      },
      codepoints(),
      SIZE
    );

    const rows = Object.entries(widths)
      .map(([c, w]) => `  ${c}: ${w},`)
      .join('\n');

    fs.writeFileSync(
      OUT,
      `'use strict';\n\n` +
        `/**\n` +
        ` * Advance widths of TH SarabunPSK, in thousandths of an em.\n` +
        ` *\n` +
        ` * Generated by scripts/build-font-widths.js from\n` +
        ` * web/public/fonts/THSarabunPSK.ttf — do not edit by hand. Thai marks that\n` +
        ` * stack on the letter before them measure 0, which is what they contribute\n` +
        ` * to a line's length.\n` +
        ` */\n\n` +
        `module.exports = {\n${rows}\n};\n`,
      'utf8'
    );
    console.log(`wrote ${OUT} (${Object.keys(widths).length} characters)`);
  } finally {
    await browser.close();
  }
})();
